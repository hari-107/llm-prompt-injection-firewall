"""Forensic PDF report for a single audit-log entry (reportlab)."""

from __future__ import annotations

import io

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

_LEVEL_COLOR = {
    "safe": colors.HexColor("#9ca3af"),
    "low": colors.HexColor("#22c55e"),
    "medium": colors.HexColor("#f59e0b"),
    "high": colors.HexColor("#ef4444"),
    "critical": colors.HexColor("#b91c1c"),
}


def _styles():
    ss = getSampleStyleSheet()
    ss.add(ParagraphStyle("Small", parent=ss["Normal"], fontSize=8, textColor=colors.grey))
    ss.add(ParagraphStyle("H", parent=ss["Heading2"], textColor=colors.HexColor("#1f2937"), spaceBefore=10))
    return ss


def build_log_report(log) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=18 * mm, bottomMargin=18 * mm)
    ss = _styles()
    flow = []

    flow.append(Paragraph("Prompt Injection Firewall — Forensic Report", ss["Title"]))
    flow.append(Paragraph(f"Request {log.request_id}", ss["Small"]))
    flow.append(Spacer(1, 8))

    level = log.risk_level or "safe"
    verdict = Table(
        [["Action", log.action.upper(), "Risk level", level.upper(), "Score", f"{log.risk_score:.4f}"]],
        colWidths=[22 * mm, 26 * mm, 24 * mm, 26 * mm, 18 * mm, 26 * mm],
    )
    verdict.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BACKGROUND", (3, 0), (3, 0), _LEVEL_COLOR.get(level, colors.grey)),
        ("TEXTCOLOR", (3, 0), (3, 0), colors.white),
        ("BACKGROUND", (0, 0), (0, 0), colors.HexColor("#1f2937")),
        ("BACKGROUND", (2, 0), (2, 0), colors.HexColor("#1f2937")),
        ("BACKGROUND", (4, 0), (4, 0), colors.HexColor("#1f2937")),
        ("TEXTCOLOR", (0, 0), (0, 0), colors.white),
        ("TEXTCOLOR", (2, 0), (2, 0), colors.white),
        ("TEXTCOLOR", (4, 0), (4, 0), colors.white),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.grey),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, colors.lightgrey),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    flow.append(verdict)

    flow.append(Paragraph("Forensic timeline &amp; metadata", ss["H"]))
    meta = [
        ["Timestamp", str(log.created_at)],
        ["Direction", log.direction],
        ["Source IP", log.ip_address or "—"],
        ["Client", f"{log.browser or '—'} / {log.os or '—'}"],
        ["Model", log.model_used or "—"],
        ["AI confidence", f"{log.ai_confidence:.4f}"],
        ["Latency", f"{log.response_time_ms} ms"],
        ["Prompt SHA-256", log.prompt_hash or "—"],
        ["Row hash (chain)", log.row_hash or "—"],
    ]
    _kv_table(flow, meta, ss)

    flow.append(Paragraph("Matched rules", ss["H"]))
    if log.matched_rules:
        _kv_table(flow, [[r, "matched"] for r in log.matched_rules], ss)
    else:
        flow.append(Paragraph("No rule matches.", ss["Normal"]))

    flow.append(Paragraph("Detected attack categories", ss["H"]))
    flow.append(Paragraph(", ".join(log.detected_attacks) or "None", ss["Normal"]))

    if log.obfuscation_flags:
        flow.append(Paragraph("Obfuscation signals", ss["H"]))
        flow.append(Paragraph(", ".join(log.obfuscation_flags), ss["Normal"]))

    if log.sanitized_prompt:
        flow.append(Paragraph("Sanitized prompt", ss["H"]))
        flow.append(Paragraph(log.sanitized_prompt[:2000], ss["Normal"]))
    if log.sanitized_output:
        flow.append(Paragraph("Masked output", ss["H"]))
        flow.append(Paragraph(log.sanitized_output[:2000], ss["Normal"]))

    flow.append(Paragraph("Recommended remediation", ss["H"]))
    flow.append(Paragraph(_remediation(log), ss["Normal"]))

    flow.append(Spacer(1, 10))
    flow.append(Paragraph(
        "Generated by the LLM Prompt Injection Firewall. Integrity is protected "
        "by a per-row SHA-256 hash chain; verify via the audit-log chain check.",
        ss["Small"],
    ))

    doc.build(flow)
    return buf.getvalue()


def _kv_table(flow, rows, ss):
    t = Table([[Paragraph(str(k), ss["Small"]), Paragraph(str(v), ss["Normal"])] for k, v in rows],
              colWidths=[45 * mm, 120 * mm])
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, colors.lightgrey),
        ("BOX", (0, 0), (-1, -1), 0.25, colors.lightgrey),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    flow.append(t)


def _remediation(log) -> str:
    if log.action == "block":
        return ("Request was blocked. Confirm the offending pattern, keep the source "
                "under rate-limit watch, and review for repeated probing from the same IP/user.")
    if log.action == "sanitize":
        return ("Malicious spans were redacted while preserving the legitimate request. "
                "Verify the sanitized text before forwarding to the model.")
    if log.action == "warn":
        return "Low-risk signals present. Monitor; no automatic action was taken beyond flagging."
    return "No malicious signals detected. No action required."
